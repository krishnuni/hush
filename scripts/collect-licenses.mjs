import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const fallback = await readFile('third-party/licenses/isarray-MIT.txt', 'utf8');
const mitTerms = fallback
  .split('\n')
  .filter((line) => !line.startsWith('Copyright (c)'))
  .join('\n');
const inherited = {
  '@types/localforage': 'node_modules/localforage/LICENSE',
};
const parts = [
  'Hush third-party notices\n\nApplication dependencies retain their upstream licenses. This document collects package notices and the bundled font license. Optional desktop neural model/voice attribution is distributed with its separate voice pack.\n',
];
let count = 0;
for (const [path, metadata] of Object.entries(lock.packages).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  if (!path.startsWith('node_modules/') || path.split('/').includes('..') || metadata.dev) continue;
  const root = resolve(path);
  const pkg = await readFile(resolve(root, 'package.json'), 'utf8')
    .then(JSON.parse)
    .catch(() => null);
  if (!pkg) continue;
  // Transformers' Node-only image and inference binaries are not shipped in the browser bundle.
  if (pkg.name === 'onnxruntime-node' || pkg.name === 'sharp' || pkg.name.startsWith('@img/sharp-'))
    continue;
  const files = (await readdir(root)).filter((name) =>
    /^(licen[cs]e|copying|copyright|notice)(\.|$|-)/i.test(name),
  );
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  parts.push(
    `\n${'='.repeat(64)}\n${pkg.name} ${pkg.version}\nDeclared license: ${pkg.license ?? 'See included terms'}\nSource: ${repository ?? pkg.homepage ?? 'See npm package metadata'}\n`,
  );
  if (files.length) {
    for (const name of files.sort())
      parts.push(`\n${name}\n${await readFile(resolve(root, name), 'utf8')}`);
  } else if (pkg.name.startsWith('@napi-rs/canvas-'))
    parts.push(await readFile('node_modules/@napi-rs/canvas/LICENSE', 'utf8'));
  else if (inherited[pkg.name]) parts.push(await readFile(inherited[pkg.name], 'utf8'));
  else if (pkg.name === 'isarray') parts.push(fallback);
  else if (pkg.license === 'MIT') {
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
    parts.push(
      `Upstream package declares MIT but supplies no separate license text or copyright year.\nDeclared author: ${author ?? 'See upstream source'}.\nStandard MIT terms follow; no copyright holder/year is inferred.\n\n${mitTerms}`,
    );
  } else if (pkg.name === 'guid-typescript' && pkg.license === 'ISC') {
    parts.push(
      `Upstream declares ISC; author: ${pkg.author}. No separate copyright notice is supplied in this package.\n\nPermission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted, provided that the above copyright notice and this permission notice appear in all copies.\n\nTHE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF OR IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.\n`,
    );
  } else throw new Error(`Missing distribution notice for ${pkg.name}.`);
  count++;
}
parts.push(`\n${'='.repeat(64)}\nNoto fonts\n${await readFile('public/fonts/OFL.txt', 'utf8')}`);
for (const family of ['Newsreader', 'IBMPlexSans'])
  parts.push(
    `\n${'='.repeat(64)}\n${family} (self-hosted WOFF2; lossless format conversion from upstream variable TTF)\nSource: https://github.com/google/fonts/tree/main/ofl/${family === 'Newsreader' ? 'newsreader' : 'ibmplexsans'}\n${await readFile(`third-party/licenses/${family}-OFL.txt`, 'utf8')}`,
  );

parts.push(
  `\n${'='.repeat(64)}\neSpeak NG in phonemizer.js (text-to-phoneme processing only)\nThe JavaScript wrapper declares Apache-2.0; the embedded eSpeak NG component is GPL-3.0-or-later.\nUpstream source and build instructions: https://github.com/xenova/phonemizer.js and https://github.com/espeak-ng/espeak-ng\nThe neural waveform is generated by Kokoro. No eSpeak system voice is used as a narration fallback.\n${await readFile('third-party/licenses/espeak-ng-GPL-3.0.txt', 'utf8')}`,
);
parts.push(
  `\n${'='.repeat(64)}\nKokoro-82M v1.0 ONNX q8 and Heart voice\nSource: https://huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX/tree/1939ad2a8e416c0acfeecc08a694d14ef25f2231\nModel and fixed voice supplied by hexgrad / ONNX Community under Apache-2.0. Model files are downloaded at build time, then served statically; they are not committed to the source repository.\n`,
);
await writeFile('public/THIRD_PARTY_NOTICES.txt', parts.join('\n'));
console.log(`Collected notices for ${count} installed runtime packages and the bundled fonts.`);
